/** A text's pixels as rows of booleans (5 rows; 4 columns a letter with the gap): for drawing words out of things, like a marching band. */
export function glyphMask(text: string): boolean[][] {
  const rows: boolean[][] = [[], [], [], [], []];
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    for (let r = 0; r < 5; r++) rows[r].push(g[r * 3] === '1', g[r * 3 + 1] === '1', g[r * 3 + 2] === '1', false);
  }
  for (const r of rows) r.pop(); // no gap after the last letter
  return rows;
}

export function textWidth(text: string, scale = 1): number {
  return text.length * 4 * scale - scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D, text: string, x: number, y: number,
  opts: { scale?: number; color?: string; shadow?: string; align?: 'left' | 'center' | 'right' } = {},
): void {
  const scale = opts.scale ?? 1;
  const align = opts.align ?? 'left';
  const w = textWidth(text, scale);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  // the 5x7 font when its pixels land on whole canvas pixels (the HD grid), else the 3x5 one
  const a = ctx.getTransform().a, sub = (2 * scale) / 3, dev = a * sub;
  const fine = dev >= 1 && Math.abs(dev - Math.round(dev)) < 0.01;
  const pass = (ox: number, oy: number, color: string) => {
    ctx.fillStyle = color;
    let px = cx;
    for (const ch of text.toUpperCase()) {
      if (fine) {
        const g = FINE[ch] ?? FINE[' '];
        for (let r = 0; r < 7; r++) { // a row at a time, runs of pixels as one rectangle
          let c = 0;
          while (c < 5) {
            if (g[r * 5 + c] !== '1') { c++; continue; }
            const c0 = c;
            while (c < 5 && g[r * 5 + c] === '1') c++;
            ctx.fillRect(px + c0 * sub + ox, cy + r * sub + oy, (c - c0) * sub, sub);
          }
        }
      } else {
        const g = GLYPHS[ch] ?? GLYPHS[' '];
        for (let i = 0; i < 15; i++) {
          if (g[i] === '1') ctx.fillRect(px + (i % 3) * scale + ox, cy + Math.floor(i / 3) * scale + oy, scale, scale);
        }
      }
      px += 4 * scale;
    }
  };
  const sh = fine ? sub : scale; // the shadow: one pixel of whichever font
  if (opts.shadow) pass(sh, sh, opts.shadow);
  pass(0, 0, opts.color ?? '#fff1e8');
}
